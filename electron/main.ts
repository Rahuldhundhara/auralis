/**
 * GNOME only shows StatusNotifier/AppIndicator icons when the AppIndicator
 * extension is installed. Detecting the watcher prevents an invisible
 * background process when close-to-tray is enabled but no tray is visible.
 */
function linuxTrayHostAvailable(): boolean {
  try {
    const result = spawnSync('busctl', ['--user', 'status', 'org.kde.StatusNotifierWatcher'], {
      timeout: 1500,
      stdio: 'ignore',
    });
    // If busctl itself is unavailable we cannot probe; try the tray and let
    // Electron decide rather than silently disabling the feature.
    if (result.error) return true;
    return result.status === 0;
  } catch {
    return true;
  }
}

function createTray() {
  if (tray || !settingsStore.get().trayEnabled) return;
  if (process.platform === 'linux' && !linuxTrayHostAvailable()) {
    trayAvailable = false;
    console.info('[auralis] no StatusNotifier tray host found; tray icon disabled for this session');
    return;
  }
  const icon = trayPath() || iconPath();
  const image = icon ? nativeImage.createFromPath(icon).resize({ width: 20, height: 20 }) : nativeImage.createEmpty();
  try {
    tray = new Tray(image);
    trayAvailable = true;
  } catch (error) {
    tray = null;
    trayAvailable = false;
    console.warn('[auralis] could not create tray icon', error);
    return;
  }
  tray.setToolTip('Auralis');
  tray.setContextMenu(
    Menu.buildFromTemplate([
      { label: 'Open Auralis', click: () => showWindow() },
      { type: 'separator' },
      { label: 'Home', click: () => { showWindow(); broadcast('navigate', '/home'); } },
      { label: 'Library', click: () => { showWindow(); broadcast('navigate', '/library'); } },
      { label: 'Search', click: () => { showWindow(); broadcast('navigate', '/search'); } },
      { type: 'separator' },
      { label: 'Play / Pause', click: () => broadcast('media-key', 'play-pause') },
      { label: 'Next track', click: () => broadcast('media-key', 'next') },
      { label: 'Previous track', click: () => broadcast('media-key', 'previous') },
      { label: 'Like current track', click: () => broadcast('media-key', 'like') },
      { type: 'separator' },
      { label: 'Quit', click: () => { quitting = true; app.quit(); } },
    ]),
  );
  tray.on('double-click', () => showWindow());
}

