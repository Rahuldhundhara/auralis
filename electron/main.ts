function rangeTotal(response: Response): number | undefined {
  const value = response.headers.get('content-range') || '';
  const match = /\/(\d+)$/.exec(value);
  return match ? Number(match[1]) : undefined;
}

const FIRST_STREAM_CHUNK = 999_999;

async function streamFastThenFallback(
  remote: string,
  headers: Record<string, string>,
  fallback: Promise<string | undefined>,
): Promise<Response> {
  // googlevideo rejects ranges larger than roughly one megabyte on some
  // clients (notably podcast episodes) with a 403. Stay just below that
  // limit; if a URL is stricter still, retry with progressively smaller
  // first chunks before paying the yt-dlp fallback latency.
  const first = await net.fetch(remote, {
    headers: { ...headers, Range: `bytes=0-${FIRST_STREAM_CHUNK}` },
    method: 'GET',
  }).catch(() => null);
  if (!first || !first.ok || !first.body) {
    const fallbackUrl = await fallback;
    if (!fallbackUrl) return first ? withCors(first) : new Response('Media request failed', { status: 502 });
    const response = await net.fetch(fallbackUrl, { headers, method: 'GET' });
    return withCors(response);
  }
  // Some origins ignore the Range header and send the complete file with a
  // 200. That body cannot be capped, so pass it through without adding a
  // fallback wait at the end of the track.
  if (first.status === 200) return withCors(first);
  const total = rangeTotal(first);
  const contentType = first.headers.get('content-type') || 'audio/webm';
  let cancelled = false;
  const stream = new ReadableStream<Uint8Array>({
    async start(controller) {
      try {
        let sent = 0;
        const reader = first.body!.getReader();
        while (!cancelled) {
          const { done, value } = await reader.read();
          if (done) break;
          if (value?.byteLength) {
            sent += value.byteLength;
            controller.enqueue(value);
          }
        }
        if (cancelled) return;

        // A range response that delivered the whole file needs no splice.
        if (total && sent >= total) {
          controller.close();
          return;
        }

        const fallbackUrl = await fallback;
        if (cancelled) return;
        if (!fallbackUrl) {
          // With a known total, a short body is a truncated response, not the
          // end of the track. Surface it so the player retries instead of
          // silently advancing to the next song.
          if (total && sent < total) throw new Error('Stream ended before the full track was delivered.');
          controller.close();
          return;
        }

        const rest = await net.fetch(fallbackUrl, {
          headers: { ...headers, Range: `bytes=${sent}-` },
          method: 'GET',
        });
        // 416 means the first body already contained every byte. Some fast
        // URLs answer a range request with the whole file.
        if (rest.status === 416) {
          controller.close();
          return;
        }
        if (!rest.ok || !rest.body) {
          throw new Error(`Stream continuation failed (${rest.status})`);
        }

        // Some origins ignore the Range header and answer 200 with the file
        // from byte 0. Skip the prefix we already sent so playback stays
        // continuous instead of splicing duplicate audio into the stream.
        let skip = 0;
        if (rest.status === 200) {
          skip = sent;
        } else {
          const restRange = /bytes\s+(\d+)-/i.exec(rest.headers.get('content-range') || '');
          const restStart = restRange ? Number(restRange[1]) : 0;
          if (restStart > sent) throw new Error('Stream continuation has a gap.');
          if (restStart < sent) skip = sent - restStart;
        }
        let delivered = sent;
        let skipped = 0;
        const restReader = rest.body.getReader();
        while (!cancelled) {
          const { done, value } = await restReader.read();
          if (done) break;
          if (!value?.byteLength) continue;
          let chunk = value;
          if (skipped < skip) {
            const take = Math.min(skip - skipped, chunk.byteLength);
            skipped += take;
            chunk = chunk.subarray(take);
            if (!chunk.byteLength) continue;
          }
          delivered += chunk.byteLength;
          controller.enqueue(chunk);
        }
        if (cancelled) return;
        if (total && delivered < total) {
          throw new Error('Stream ended before the full track was delivered.');
        }
        controller.close();
      } catch (error) {
        if (!cancelled) {
          try {
            controller.error(error);
          } catch {
            // The response was cancelled while the error was being reported.
          }
        }
      }
    },
    cancel() {
      cancelled = true;
    },
  });
  const outputHeaders = new Headers({
    'Content-Type': contentType,
    'Accept-Ranges': 'bytes',
  });
  // A 206 with an explicit Content-Range is what makes Chromium treat the
  // resource as genuinely seekable. A bare 200 (even with Accept-Ranges) left
  // the element reporting an empty `seekable` range on some streams, so every
  // forward drag restarted at 0.
  if (total) {
    outputHeaders.set('Content-Length', String(total));
    outputHeaders.set('Content-Range', `bytes 0-${total - 1}/${total}`);
  }
  return withCors(new Response(stream, { status: total ? 206 : 200, headers: outputHeaders }));
}

function mediaMime(filePath: string): string {
  switch (path.extname(filePath).toLowerCase()) {
    case '.mp3': return 'audio/mpeg';
    case '.m4a':
    case '.aac': return 'audio/mp4';
    case '.opus': return 'audio/ogg';
    case '.ogg': return 'audio/ogg';
    case '.webm': return 'audio/webm';
    case '.flac': return 'audio/flac';
    case '.wav': return 'audio/wav';
    default: return 'application/octet-stream';
  }
}

/**
 * Serve a local audio file with proper `Accept-Ranges` / `206 Content-Range`
 * semantics. Without this, the `<audio>` element treats cached and downloaded
 * tracks as unseekable and every seek restarts from the beginning.
 */
function serveLocalMedia(request: Request, filePath: string): Response {
  const stat = fs.statSync(filePath);
  const total = stat.size;
  const type = mediaMime(filePath);
  const baseHeaders: Record<string, string> = {
    'Content-Type': type,
    'Accept-Ranges': 'bytes',
    'Cache-Control': 'no-store',
  };
  const range = request.headers.get('range');
  const match = range ? /^bytes=(\d*)-(\d*)$/i.exec(range.trim()) : null;
  if (match && (match[1] || match[2])) {
    let start = match[1] ? Number(match[1]) : 0;
    let end = match[2] ? Number(match[2]) : total - 1;
    if (!match[1] && match[2]) {
      // Suffix range: last N bytes.
      start = Math.max(0, total - Number(match[2]));
      end = total - 1;
    }
    if (!Number.isFinite(start) || start >= total) {
      return withCors(new Response(null, {
        status: 416,
        headers: { 'Content-Range': `bytes */${total}` },
      }));
    }
    end = Math.min(Math.max(end, start), total - 1);
    const body = Readable.toWeb(fs.createReadStream(filePath, { start, end })) as unknown as ReadableStream;
    return withCors(new Response(body, {
      status: 206,
      headers: {
        ...baseHeaders,
        'Content-Range': `bytes ${start}-${end}/${total}`,
        'Content-Length': String(end - start + 1),
      },
    }));
  }
  const body = Readable.toWeb(fs.createReadStream(filePath)) as unknown as ReadableStream;
  return withCors(new Response(body, {
    status: 200,
    headers: { ...baseHeaders, 'Content-Length': String(total) },
  }));
}

/**
 * Artwork is small, immutable and requested repeatedly (card, hero, player,
 * palette extraction). A tiny memory + disk cache removes the visible
 * "cover buffering" on slow CDN days and makes returning to a page instant.
 */
const IMAGE_MEMORY_MAX_BYTES = 96 * 1024 * 1024;
const IMAGE_MEMORY_MAX_ENTRIES = 240;
const IMAGE_DISK_MAX_BYTES = 256 * 1024 * 1024;
const IMAGE_CACHE_TTL = 7 * 24 * 60 * 60_000;

interface CachedImage {
  at: number;
  type: string;
  body: Buffer;
}

const imageMemory = new Map<string, CachedImage>();
/** Short-lived failures stop a dead CDN URL from being retried by every card. */
const imageFailures = new Map<string, number>();
const IMAGE_FAILURE_TTL = 60_000;
const inflightImages = new Map<string, Promise<Response>>();
let imageMemoryBytes = 0;
let imageSlots = 0;
const imageWaiters: Array<() => void> = [];
const IMAGE_MAX_CONCURRENT = 6;
let imageCacheDirValue: string | null = null;
let imageDiskPruneTimer: NodeJS.Timeout | null = null;
let imageDiskQueue: Promise<void> = Promise.resolve();

function imageCacheDir(): string {
  if (!imageCacheDirValue) imageCacheDirValue = path.join(app.getPath('userData'), 'image-cache');
  return imageCacheDirValue;
}

function imageCacheKey(remote: string): string {
  return crypto.createHash('sha1').update(remote).digest('hex');
}

function rememberImage(remote: string, entry: CachedImage) {
  const previous = imageMemory.get(remote);
  if (previous) imageMemoryBytes -= previous.body.length;
  imageMemory.set(remote, entry);
  imageMemoryBytes += entry.body.length;
  while (imageMemory.size > IMAGE_MEMORY_MAX_ENTRIES || imageMemoryBytes > IMAGE_MEMORY_MAX_BYTES) {
    const oldestKey = imageMemory.keys().next().value;
    if (!oldestKey) break;
    const oldest = imageMemory.get(oldestKey);
    imageMemory.delete(oldestKey);
    imageMemoryBytes -= oldest?.body.length ?? 0;
  }
}

function queueImageDiskWrite(remote: string, entry: CachedImage) {
  const base = path.join(imageCacheDir(), imageCacheKey(remote));
  imageDiskQueue = imageDiskQueue
    .then(async () => {
      await fs.promises.mkdir(imageCacheDir(), { recursive: true });
      await fs.promises.writeFile(`${base}.img`, entry.body);
      await fs.promises.writeFile(`${base}.type`, entry.type);
    })
    .catch(() => undefined);
  if (!imageDiskPruneTimer) {
    imageDiskPruneTimer = setTimeout(() => {
      imageDiskPruneTimer = null;
      void pruneImageDisk();
    }, 8_000);
    imageDiskPruneTimer.unref?.();
  }
}

async function pruneImageDisk() {
  try {
    const dir = imageCacheDir();
    const names = await fs.promises.readdir(dir);
    const now = Date.now();
    const files: { path: string; at: number; size: number }[] = [];
    for (const name of names) {
      if (!name.endsWith('.img')) continue;
      const filePath = path.join(dir, name);
      const stat = await fs.promises.stat(filePath).catch(() => null);
      if (!stat) continue;
      if (now - stat.mtimeMs > IMAGE_CACHE_TTL) {
        await fs.promises.rm(filePath, { force: true }).catch(() => undefined);
        await fs.promises.rm(`${filePath.slice(0, -4)}.type`, { force: true }).catch(() => undefined);
        continue;
      }
      files.push({ path: filePath, at: stat.mtimeMs, size: stat.size });
    }
    let total = files.reduce((sum, file) => sum + file.size, 0);
    if (total <= IMAGE_DISK_MAX_BYTES) return;
    files.sort((a, b) => a.at - b.at);
    for (const file of files) {
      if (total <= IMAGE_DISK_MAX_BYTES) break;
      await fs.promises.rm(file.path, { force: true }).catch(() => undefined);
      await fs.promises.rm(`${file.path.slice(0, -4)}.type`, { force: true }).catch(() => undefined);
      total -= file.size;
    }
  } catch {
    // A cache prune must never break image loading.
  }
}

async function readImageCache(remote: string): Promise<CachedImage | null> {
  const memory = imageMemory.get(remote);
  if (memory && Date.now() - memory.at <= IMAGE_CACHE_TTL) return memory;
  try {
    const base = path.join(imageCacheDir(), imageCacheKey(remote));
    const [body, type, stat] = await Promise.all([
      fs.promises.readFile(`${base}.img`),
      fs.promises.readFile(`${base}.type`, 'utf8').catch(() => 'image/jpeg'),
      fs.promises.stat(`${base}.img`),
    ]);
    if (!body.length || Date.now() - stat.mtimeMs > IMAGE_CACHE_TTL) return null;
    const entry: CachedImage = { at: stat.mtimeMs, type: type.trim() || 'image/jpeg', body };
    rememberImage(remote, entry);
    return entry;
  } catch {
    return null;
  }
}

function imageResponse(entry: CachedImage): Response {
  return withCors(
    new Response(new Uint8Array(entry.body), {
      status: 200,
      headers: {
        'Content-Type': entry.type,
        'Content-Length': String(entry.body.length),
        'Cache-Control': 'public, max-age=604800, immutable',
      },
    }),
  );
}

function acquireImageSlot(): Promise<void> {
  if (imageSlots < IMAGE_MAX_CONCURRENT) {
    imageSlots += 1;
    return Promise.resolve();
  }
  return new Promise((resolve) => imageWaiters.push(() => {
    imageSlots += 1;
    resolve();
  }));
}

function releaseImageSlot(): void {
  const next = imageWaiters.shift();
  if (next) next();
  else imageSlots -= 1;
}

interface RemoteImage {
  status: number;
  type: string;
  body: Buffer;
}

/**
 * Download a cover with plain Node HTTP. Unlike the renderer-facing fetch
 * path this cannot be stalled by custom-protocol scheduling, and an explicit
 * socket timeout keeps one slow CDN host from consuming an image slot.
 */
function downloadRemoteImage(
  remote: string,
  headers: Record<string, string>,
  redirects = 3,
): Promise<RemoteImage> {
  return new Promise((resolve, reject) => {
    let url: URL;
    try {
      url = new URL(remote);
    } catch (error) {
      reject(error);
      return;
    }
    const client = url.protocol === 'https:' ? https : http;
    const request = client.get(url, { headers }, (response) => {
      const status = response.statusCode || 0;
      if ([301, 302, 303, 307, 308].includes(status) && response.headers.location) {
        response.resume();
        if (redirects <= 0) {
          reject(new Error('too many image redirects'));
          return;
        }
        const next = new URL(response.headers.location, url).toString();
        downloadRemoteImage(next, headers, redirects - 1).then(resolve, reject);
        return;
      }
      const chunks: Buffer[] = [];
      let size = 0;
      response.on('data', (chunk: Buffer) => {
        size += chunk.length;
        if (size > 8 * 1024 * 1024) {
          request.destroy(new Error('image too large'));
          return;
        }
        chunks.push(chunk);
      });
      response.on('end', () => {
        resolve({
          status,
          type: response.headers['content-type'] || 'image/jpeg',
          body: Buffer.concat(chunks),
        });
      });
      response.on('error', reject);
    });
    request.setTimeout(9_000, () => request.destroy(new Error('image timeout')));
    request.on('error', reject);
  });
}

async function serveImage(remote: string, headers: Record<string, string>): Promise<Response> {
  const failedAt = imageFailures.get(remote);
  if (failedAt && Date.now() - failedAt < IMAGE_FAILURE_TTL) {
    return withCors(new Response('Image temporarily unavailable', { status: 502 }));
  }
  const existing = inflightImages.get(remote);
  if (existing) return existing;

  const task = (async () => {
    await acquireImageSlot();
    try {
      const cached = await readImageCache(remote);
      if (cached) return imageResponse(cached);
      // YouTube's CDN is burst-sensitive: retry once before declaring the
      // cover unavailable rather than tripling the request rate on a blip.
      let lastStatus = 502;
      for (let attempt = 0; attempt < 2; attempt += 1) {
        try {
          const image = await downloadRemoteImage(remote, headers);
          lastStatus = image.status;
          if (image.status >= 200 && image.status < 300 && image.body.length) {
            const entry: CachedImage = { at: Date.now(), type: image.type, body: image.body };
            rememberImage(remote, entry);
            queueImageDiskWrite(remote, entry);
            imageFailures.delete(remote);
            return imageResponse(entry);
          }
        } catch {
          // Fall through to the retry.
        }
        if (attempt < 1) await new Promise((resolve) => setTimeout(resolve, 350));
      }
      imageFailures.set(remote, Date.now());
      const status = lastStatus >= 400 && lastStatus <= 599 ? lastStatus : 502;
      return withCors(new Response('Image fetch failed', { status }));
    } finally {
      releaseImageSlot();
      inflightImages.delete(remote);
    }
  })();

  inflightImages.set(remote, task);
  return task;
}

function registerMediaProtocol() {
  protocol.handle('auralis-media', async (request) => {
    try {
      const url = new URL(request.url);
      if (url.host === 'local') {
        const filePath = decodeURIComponent(url.pathname.replace(/^\//, ''));
        if (!filePath || !fs.existsSync(filePath) || !isAllowedLocalMedia(filePath)) {
          return new Response('Not found', { status: 404 });
        }
        // Serve local/cached audio ourselves so the media element always sees
        // a real byte-range response. `net.fetch(file://)` does not advertise
        // range support, which left downloaded and cached tracks unseekable —
        // dragging their progress bar snapped straight back to the start.
        return serveLocalMedia(request, filePath);
      }
      if (url.host === 'image') {
        const encoded = url.pathname.replace(/^\//, '');
        const remote = Buffer.from(encoded, 'base64url').toString('utf8');
        if (!isAllowedImageUrl(remote)) return new Response('Bad request', { status: 400 });
        const headers: Record<string, string> = {
          'User-Agent':
            'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36',
          Referer: 'https://music.youtube.com/',
          Accept: 'image/avif,image/webp,image/*,*/*;q=0.8',
        };
        const response = await serveImage(remote, headers);
        return response;
      }
      if (url.host === 'stream') {
        const encoded = url.pathname.replace(/^\//, '');
        const remote = Buffer.from(encoded, 'base64url').toString('utf8');
        if (!isAllowedStreamUrl(remote)) return new Response('Bad request', { status: 400 });
        const headers: Record<string, string> = {
          'User-Agent':
            'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36',
          Referer: 'https://music.youtube.com/',
          Origin: 'https://music.youtube.com',
        };
        const range = request.headers.get('range');
        const rangeMatch = range ? /^bytes=(\d+)-/i.exec(range.trim()) : null;
        const start = rangeMatch ? Number(rangeMatch[1]) : 0;
        const suffixRange = range ? /^bytes=-\d+$/i.test(range.trim()) : false;
        // Only the open-ended `bytes=0-` request uses the fast-then-fallback
        // splice. A bounded range is proxied directly so we never return more
        // bytes than the caller asked for.
        const openEnded = !range || /^bytes=0-$/i.test(range.trim());
        const fallback = start === 0 && !suffixRange && openEnded ? fallbackStreamTask(remote) : undefined;
        if (fallback) {
          // A fast player URL only supports its first range. Deliver a
          // continuous response (fast first chunk followed by the full-range
          // yt-dlp stream) so the media element never sees a false EOF.
          return streamFastThenFallback(remote, headers, fallback);
        }
        // Fast Innertube URLs only accept their first range. Later requests
        // (seeks and container suffixes) use the full-range yt-dlp URL,
        // which accepts any range.
        const target =
          start > 0 || suffixRange
            ? (await fallbackStreamUrl(remote)) || remote
            : remote;
        if (range) headers.Range = range;
        const response = await net.fetch(target, { headers, method: 'GET' });
        return withCors(response);
      }
      return new Response('Not found', { status: 404 });
    } catch (error: any) {
      return new Response(error?.message || 'Media request failed', { status: 502 });
    }
  });
}

function withCors(response: Response): Response {
  const headers = new Headers(response.headers);
  headers.set('Access-Control-Allow-Origin', '*');
  headers.set('Access-Control-Allow-Headers', 'Range');
  headers.set('Access-Control-Expose-Headers', 'Content-Length, Content-Range, Accept-Ranges');
  return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
}

async function openEmbeddedLoginWindow(): Promise<SessionState> {
  if (loginWindow) {
    loginWindow.focus();
    return ytm.session();
  }
  const partition = 'persist:auralis-login';
  const loginSession = session.fromPartition(partition);
  const userAgent =
    'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36';
  loginSession.setUserAgent(userAgent);
  loginWindow = new BrowserWindow({
    width: 560,
    height: 760,
    parent: mainWindow || undefined,
    modal: false,
    title: 'Sign in to YouTube Music',
    autoHideMenuBar: true,
    webPreferences: {
      partition,
      nodeIntegration: false,
      contextIsolation: true,
      sandbox: true,
    },
  });
  loginWindow.webContents.setUserAgent(userAgent);

  return new Promise<SessionState>((resolve) => {
    let settled = false;
    const complete = (state: SessionState) => {
      if (settled) return;
      settled = true;
      resolve(state);
    };
    const finish = async () => {
      try {
        const cookies = await loginSession.cookies.get({ domain: '.youtube.com' });
        const names = new Map<string, string>();
        for (const cookie of cookies) {
          if (!cookie.name || !cookie.value) continue;
          if (cookie.domain?.includes('youtube.com')) names.set(cookie.name, cookie.value);
        }
        if (!names.has('SAPISID') && !names.has('__Secure-3PAPISID') && !names.has('SID')) return false;
        const cookie = [...names.entries()].map(([name, value]) => `${name}=${value}`).join('; ');
        const state = await ytm.setCookies(cookie);
        broadcast('session-change', state);
        complete(state);
        loginWindow?.close();
        loginWindow = null;
        return true;
      } catch {
        return false;
      }
    };

    loginWindow!.webContents.on('did-navigate', async (_event, url) => {
      if (!/^https:\/\/(music|www)\.youtube\.com\//.test(url)) return;
      await finish();
    });
    loginWindow!.webContents.on('did-redirect-navigation', async (_event, url) => {
      if (!/^https:\/\/(music|www)\.youtube\.com\//.test(url)) return;
      await finish();
    });
    loginWindow!.on('closed', () => {
      loginWindow = null;
      complete(ytm.session());
    });
    loginWindow!.loadURL(
      'https://accounts.google.com/ServiceLogin?service=youtube&passive=true&continue=https%3A%2F%2Fmusic.youtube.com%2F&flowName=GlifWebSignIn',
    ).catch(() => {
      loginWindow?.close();
      complete(ytm.session());
    });
  });
}

/**
 * Linux keeps the old embedded fallback for machines without Chrome, but a
 * real Chrome window avoids Google's "This browser or app may not be secure"
 * block. The normal Chrome profile is never touched.
 */
async function openLoginWindow(): Promise<SessionState> {
  if (process.platform === 'linux' && findChrome()) {
    try {
      const state = await openChromeLogin();
      broadcast('session-change', state);
      return state;
    } catch (error) {
      console.warn('[auralis] Chrome sign-in failed; using embedded window:', error);
    }
  }
  return openEmbeddedLoginWindow();
}

function settingsPatchHandlers() {
  ipcMain.handle('settings:set', (_event, patch: Partial<Settings>) => {
    const previous = settingsStore.get();
    const merged = settingsStore.update((current) => mergeSettings(current, patch));
    if (merged.theme !== previous.theme) applyTheme(merged.theme);
    if (merged.trayEnabled !== previous.trayEnabled) {
      if (merged.trayEnabled) createTray();
      else destroyTray();
    }
    if (merged.language !== previous.language || merged.region !== previous.region) {
      innertube.setLocale({ hl: merged.language || 'en', gl: merged.region || 'US' });
    }
    broadcast('settings-change', merged);
    return merged;
  });
  ipcMain.handle('settings:reset', () => {
    const merged = settingsStore.set(structuredClone(DEFAULT_SETTINGS));
    applyTheme(merged.theme);
    if (merged.trayEnabled) createTray();
    else destroyTray();
    broadcast('settings-change', merged);
    return merged;
  });
}

function parsePlaylistId(input: string): string {
  const raw = (input || '').trim();
  if (!raw) throw new Error('Paste a YouTube or YouTube Music playlist link.');
  if (!raw.includes('/') && /^[A-Za-z0-9_-]{10,}$/.test(raw)) return raw.replace(/^VL/, '');
  let url: URL;
  try {
    url = new URL(/^https?:\/\//i.test(raw) ? raw : `https://${raw}`);
  } catch {
    throw new Error('That does not look like a playlist link.');
  }
  if (!/(^|\.)youtube\.com$|(^|\.)youtu\.be$/i.test(url.hostname)) {
    throw new Error('Only YouTube and YouTube Music playlist links are supported.');
  }
  const list = url.searchParams.get('list');
  if (!list) throw new Error('This link does not contain a playlist id.');
  return list.replace(/^VL/, '');
}

function tracksFromBrowse(page: { shelves: Array<{ items: Array<{ track?: Track }> }> }): Track[] {
  return page.shelves.flatMap((shelf) => shelf.items.map((item) => item.track).filter((track): track is Track => Boolean(track)));
}

function mergeSettings(current: Settings, patch: Partial<Settings>): Settings {
  const next: Settings = { ...current, ...patch };
  if (patch.eq) {
    next.eq = { ...current.eq, ...patch.eq, bands: patch.eq.bands ? [...patch.eq.bands] : current.eq.bands };
    next.eq.preamp = Math.min(12, Math.max(-12, Number(next.eq.preamp) || 0));
    next.eq.bassBoost = Math.min(12, Math.max(-12, Number(next.eq.bassBoost) || 0));
    next.eq.bands = next.eq.bands.map((value) => Math.min(12, Math.max(-12, Number(value) || 0)));
  }
  if (patch.lastfm) next.lastfm = { ...current.lastfm, ...patch.lastfm };
  if (patch.discord) next.discord = { ...current.discord, ...patch.discord };
  if (patch.translation) next.translation = { ...current.translation, ...patch.translation };
  next.volume = Math.min(1, Math.max(0, Number(next.volume) || 0));
  next.playbackRate = Math.min(2, Math.max(0.5, Number(next.playbackRate) || 1));
  return next;
}

