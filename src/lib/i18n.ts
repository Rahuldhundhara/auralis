export function storedLanguage(settings: Settings): LanguageCode {
  const lang = (settings.personalization?.uiLanguage || settings.language || 'en') as LanguageCode;
  return Object.prototype.hasOwnProperty.call(LANGUAGE_NAMES, lang) ? lang : 'en';
}

export function t(key: string, language: LanguageCode = 'en'): string {
  const dict = DICTIONARY[language] || DICTIONARY.en;
  const value = dict[key];
  if (value) return value;
  return DICTIONARY.en[key] || key;
}

export function tStep(key: string, language: LanguageCode, step: number, total: number): string {
  return t(key, language).replace('{{step}}', String(step)).replace('{{total}}', String(total));
}

/** Reads the active UI language from the app store settings. */
export function useLanguage(): LanguageCode {
  return storedLanguage(useAppStore.getState().settings);
}

export function useTranslation() {
  const language = useLanguage();
  return { language, t: (key: string) => t(key, language) };
}
